/**
 * Internal: the unicode values of the characters of a system.
 */
export default interface IUnicodes {
  /** The unicode character number that represents the `zero` character value in the set */
  zeroUnicodeNumber: number;
  /** The unicode character number that represents the `first` character value in the set */
  firstUnicodeNumber: number;
  /** The unicode character number that represents the `last` character value in the set */
  lastUnicodeNumber: number;
}
